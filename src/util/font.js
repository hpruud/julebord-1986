// Procedural 8x8 bitmap font. Each glyph is 8 bytes (rows), 1 bit per pixel.
// Covers A-Z, 0-9, and a few symbols. Lowercase maps to uppercase.
const FONT = {};

function g(ch, rows) {
  // rows is an array of 8 strings of length 8 ('.' or '#')
  const bytes = new Uint8Array(8);
  for (let y = 0; y < 8; y++) {
    let b = 0;
    for (let x = 0; x < 8; x++) {
      if (rows[y][x] === '#') b |= (1 << (7 - x));
    }
    bytes[y] = b;
  }
  FONT[ch] = bytes;
}


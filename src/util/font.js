// Build atlas as a 128 x 8 single-row bitmap-ish texture-friendly Uint8Array of glyph rows.
// We'll create a 1-channel atlas: width = 8 * 128, height = 8, filled per-pixel 0/255.
export function buildFontAtlas() {
  const ATLAS_W = 8 * 128;
  const ATLAS_H = 8;
  const data = new Uint8Array(ATLAS_W * ATLAS_H * 4);
  for (let code = 0; code < 128; code++) {
    let ch = String.fromCharCode(code);
    if (ch >= 'a' && ch <= 'z') ch = ch.toUpperCase();
    const glyph = FONT[ch] || FONT[' '];
    for (let y = 0; y < 8; y++) {
      const row = glyph[y];
      for (let x = 0; x < 8; x++) {
        const px = (row >> (7 - x)) & 1;
        const idx = ((y * ATLAS_W) + (code * 8 + x)) * 4;
        const v = px ? 255 : 0;
        data[idx+0] = v;
        data[idx+1] = v;
        data[idx+2] = v;
        data[idx+3] = v;
      }
    }
  }
  return { data, w: ATLAS_W, h: ATLAS_H };
}

export function createFontTexture(gl) {
  const { data, w, h } = buildFontAtlas();
  const tex = gl.createTexture();
  gl.bindTexture(gl.TEXTURE_2D, tex);
  gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGBA8, w, h, 0, gl.RGBA, gl.UNSIGNED_BYTE, data);
  gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MIN_FILTER, gl.NEAREST);
  gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MAG_FILTER, gl.NEAREST);
  gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_S, gl.CLAMP_TO_EDGE);
  gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_T, gl.CLAMP_TO_EDGE);
  return { tex, w, h, glyphW: 8, glyphH: 8 };
}

// CPU-side draw glyph into Uint8ClampedArray RGBA framebuffer at (x,y) with color [r,g,b].
export function blitChar(buf, bw, bh, ch, x, y, r, g, b) {
  let c = ch;
  if (c >= 'a' && c <= 'z') c = c.toUpperCase();
  const glyph = FONT[c] || FONT[' '];
  for (let gy = 0; gy < 8; gy++) {
    const row = glyph[gy];
    const py = y + gy;
    if (py < 0 || py >= bh) continue;
    for (let gx = 0; gx < 8; gx++) {
      if (!((row >> (7 - gx)) & 1)) continue;
      const px = x + gx;
      if (px < 0 || px >= bw) continue;
      const idx = (py * bw + px) * 4;
      buf[idx+0] = r;
      buf[idx+1] = g;
      buf[idx+2] = b;
      buf[idx+3] = 255;
    }
  }
}

export function blitText(buf, bw, bh, text, x, y, r, g, b, spacing = 8) {
  for (let i = 0; i < text.length; i++) {
    blitChar(buf, bw, bh, text[i], x + i * spacing, y, r, g, b);
  }
}

export function textWidth(text, spacing = 8) {
  return text.length * spacing;
}
